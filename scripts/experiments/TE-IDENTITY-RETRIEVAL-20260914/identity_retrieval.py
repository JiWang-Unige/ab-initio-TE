#!/usr/bin/env python3
"""Audit and plan identity-aware TE prototype retrieval.

This module is an executable *input contract*, not a claim-grade retrieval
result.  It exists to make the proposed comparison explicit before any
large FASTA extraction, embedding pass, or classifier training is launched.

The central distinction is between a natural genomic copy, a family
consensus, and a transformed fragment.  A fragment generated by cropping a
single consensus is never promoted to an independent source copy.  Empty
``source_copy_id`` or ``homology_component_id`` values are unknown values;
they never create a positive same-copy pair.

The command line writes a compact audit and protocol plan.  Retrieval scores
are intentionally not produced here.  The optional score-calibration helper
is kept small and deterministic so a later Slurm runner can use the same
fixed CAL false-accept rule for every representation.
"""

from __future__ import annotations

import argparse
import csv
import gzip
import hashlib
import json
import math
import os
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Dict, Iterable, List, Mapping, Optional, Sequence, Tuple


CONTRACT_VERSION = "te-identity-retrieval-v1"
SEED = 42
MISSING = {"", "na", "n/a", "none", "null", "unknown", "missing", ".", "-"}
NATURAL_COPY_KINDS = {"natural_copy", "genome_copy", "training_copy"}
CONSENSUS_KINDS = {"consensus", "family_consensus"}
SPLITS = {"train", "cal", "eval"}
IDENTITY_FIELDS = (
    "host_id",
    "source_copy_id",
    "homology_component_id",
    "family_id",
    "split",
)
CONTENT_FIELDS = ("sequence", "sequence_path")


def normalize(value: object) -> str:
    """Return a trimmed token, preserving non-missing values verbatim."""

    if value is None:
        return ""
    return str(value).strip()


def missing(value: object) -> bool:
    return normalize(value).lower() in MISSING


def first_value(row: Mapping[str, object], *names: str) -> str:
    for name in names:
        if name in row and not missing(row[name]):
            return normalize(row[name])
    return ""


def open_text(path: Path):
    if path.name.endswith(".gz"):
        return gzip.open(path, "rt", encoding="utf-8")
    return path.open("r", encoding="utf-8")


def load_rows(path: Path) -> List[dict]:
    """Load TSV or JSONL without attempting to load a FASTA or checkpoint."""

    with open_text(path) as handle:
        if path.name.endswith((".jsonl", ".jsonl.gz")):
            return [json.loads(line) for line in handle if line.strip()]
        return list(csv.DictReader(handle, delimiter="\t"))


def normalize_row(row: Mapping[str, object], index: int) -> dict:
    """Map documented aliases into one explicit, auditable record schema."""

    source_kind = first_value(row, "source_kind", "kind", "provenance").lower()
    split = first_value(row, "split", "role").lower()
    if split == "test":
        split = "eval"
    return {
        "record_id": first_value(row, "record_id", "id", "fragment_id") or f"row_{index:08d}",
        "source_kind": source_kind,
        "assembly": first_value(row, "assembly", "genome", "reference"),
        "host_id": first_value(row, "host_id", "host", "species"),
        "source_copy_id": first_value(row, "source_copy_id", "copy_id", "copy"),
        "homology_component_id": first_value(
            row, "homology_component_id", "homology_id", "homology_component"
        ),
        "family_id": first_value(row, "family_id", "family", "repeat_family"),
        "family_level": first_value(row, "family_level", "level") or "family",
        "host_locus": first_value(row, "host_locus", "contig", "chromosome", "chrom"),
        "split": split,
        "sequence": first_value(row, "sequence", "seq"),
        "sequence_path": first_value(row, "sequence_path", "seq_path"),
        "embedding_path": first_value(row, "embedding_path", "embedding_file"),
        "embedding_model_id": first_value(row, "embedding_model_id", "model_id"),
        "profile_path": first_value(row, "profile_path", "hmm_path"),
        "origin_id": first_value(row, "origin_id", "consensus_id", "parent_record_id"),
        "prototype_eligible": first_value(row, "prototype_eligible").lower(),
        "input_row": index,
    }


def canonical_copy_key(row: Mapping[str, str]) -> Optional[Tuple[str, str]]:
    """Copy IDs are scoped to a host; missing IDs never form a key."""

    if missing(row["host_id"]) or missing(row["source_copy_id"]):
        return None
    return row["host_id"], row["source_copy_id"]


def canonical_homology_key(row: Mapping[str, str]) -> Optional[str]:
    if missing(row["homology_component_id"]):
        return None
    return row["homology_component_id"]


def has_content(row: Mapping[str, str]) -> bool:
    """Content may be inline or an existing local path; no remote scan occurs."""

    if not missing(row["sequence"]):
        return True
    if missing(row["sequence_path"]):
        return False
    return Path(row["sequence_path"]).is_file()


def identity_complete(row: Mapping[str, str]) -> bool:
    return row["source_kind"] in NATURAL_COPY_KINDS and all(
        not missing(row[field]) for field in IDENTITY_FIELDS
    )


def _cross_split(rows: Sequence[Mapping[str, str]], field: str) -> List[str]:
    memberships: Dict[str, set] = defaultdict(set)
    for row in rows:
        value = row[field]
        if missing(value) or missing(row["split"]):
            continue
        key = f"{row['host_id']}::{value}" if field in {"source_copy_id", "host_id"} else value
        memberships[key].add(row["split"])
    return sorted(key for key, values in memberships.items() if len(values) > 1)


def audit_manifest(rows: Iterable[Mapping[str, object]]) -> dict:
    """Audit identity, content, and split invariants without running retrieval."""

    normalized = [normalize_row(row, index) for index, row in enumerate(rows)]
    duplicate_ids = Counter(row["record_id"] for row in normalized)
    duplicate_id_count = sum(count - 1 for count in duplicate_ids.values() if count > 1)
    source_counts = Counter(row["source_kind"] or "MISSING" for row in normalized)
    missing_identity = Counter()
    missing_content = Counter()
    complete_natural = 0
    natural_rows = 0
    consensus_origin_counts = Counter()
    bad_split_values = Counter()
    for row in normalized:
        if row["source_kind"] in NATURAL_COPY_KINDS:
            natural_rows += 1
            for field in IDENTITY_FIELDS:
                if missing(row[field]):
                    missing_identity[field] += 1
            if not has_content(row):
                missing_content["natural_copy"] += 1
            if identity_complete(row):
                complete_natural += 1
        elif row["source_kind"] in CONSENSUS_KINDS:
            if not missing(row["origin_id"]):
                consensus_origin_counts[row["origin_id"]] += 1
            if not has_content(row):
                missing_content["consensus"] += 1
        else:
            if row["source_kind"]:
                if not has_content(row):
                    missing_content[row["source_kind"]] += 1
        if row["split"] and row["split"] not in SPLITS:
            bad_split_values[row["split"]] += 1

    # A host genome may legitimately supply TRAIN/CAL/EVAL copies.  A
    # chromosome/contig is a locus within that host, not a new host.  Host is
    # therefore reported as context, while source-copy and homology IDs are
    # the leakage gates.
    cross_split = {field: _cross_split(normalized, field) for field in (
        "source_copy_id", "homology_component_id"
    )}
    host_roles: Dict[str, set] = defaultdict(set)
    for row in normalized:
        if not missing(row["host_id"]) and not missing(row["split"]):
            host_roles[row["host_id"]].add(row["split"])
    consensus_copy_ids = sum(
        1
        for row in normalized
        if row["source_kind"] in CONSENSUS_KINDS
        and (not missing(row["source_copy_id"]) or not missing(row["homology_component_id"]))
    )
    blockers = []
    if duplicate_id_count:
        blockers.append("duplicate_record_ids")
    if not normalized:
        blockers.append("empty_manifest")
    if missing_identity:
        blockers.append("incomplete_natural_copy_identity")
    if bad_split_values:
        blockers.append("invalid_split_values")
    if any(cross_split.values()):
        blockers.append("cross_split_identity_overlap")
    status = "PASS_AUDIT" if not blockers else "BLOCKED_IDENTITY_FIELDS"
    if not normalized:
        status = "NOTRUN_NO_INPUT"
    elif natural_rows == 0:
        status = "NOTRUN_NO_NATURAL_COPIES"
    return {
        "contract_version": CONTRACT_VERSION,
        "status": status,
        "records": len(normalized),
        "source_kind_counts": dict(sorted(source_counts.items())),
        "natural_copy_rows": natural_rows,
        "complete_natural_copy_rows": complete_natural,
        "missing_identity_counts": {field: missing_identity.get(field, 0) for field in IDENTITY_FIELDS},
        "missing_content_counts": dict(sorted(missing_content.items())),
        "duplicate_record_id_count": duplicate_id_count,
        "consensus_rows_with_identity_ids": consensus_copy_ids,
        "consensus_origin_multiplicity": {
            key: count for key, count in sorted(consensus_origin_counts.items()) if count > 1
        },
        "invalid_split_counts": dict(sorted(bad_split_values.items())),
        "cross_split_identity_overlap": {
            field: {"count": len(values), "examples": values[:10]}
            for field, values in cross_split.items()
        },
        "host_roles": {key: sorted(values) for key, values in sorted(host_roles.items())},
        "host_is_not_chromosome": True,
        "empty_ids_are_unknown": True,
        "consensus_fragments_are_not_natural_copies": True,
        "blockers": blockers,
    }


def _group_natural(rows: Sequence[Mapping[str, str]], split: Optional[str] = None) -> Dict[str, List[dict]]:
    grouped: Dict[str, List[dict]] = defaultdict(list)
    for row in rows:
        if row["source_kind"] not in NATURAL_COPY_KINDS or not identity_complete(row):
            continue
        if split is not None and row["split"] != split:
            continue
        grouped[row["family_id"]].append(dict(row))
    return grouped


def _content_counts(rows: Sequence[Mapping[str, str]]) -> dict:
    return {
        "rows": len(rows),
        "rows_with_content": sum(1 for row in rows if has_content(row)),
        "rows_without_content": sum(1 for row in rows if not has_content(row)),
        "families": len({row["family_id"] for row in rows if not missing(row["family_id"])}),
    }


def protocol_availability(rows: Sequence[Mapping[str, object]], audit: Optional[dict] = None) -> dict:
    """Return readiness only; a READY protocol still needs a Slurm run."""

    normalized = [normalize_row(row, index) for index, row in enumerate(rows)]
    audit = audit or audit_manifest(normalized)
    natural = [row for row in normalized if row["source_kind"] in NATURAL_COPY_KINDS]
    complete = [row for row in natural if identity_complete(row)]
    eval_rows = [row for row in complete if row["split"] == "eval"]
    cal_rows = [row for row in complete if row["split"] == "cal"]
    train_rows = [row for row in complete if row["split"] == "train"]
    consensus = [row for row in normalized if row["source_kind"] in CONSENSUS_KINDS]
    consensus_families = sorted({row["family_id"] for row in consensus if not missing(row["family_id"])})
    train_groups = _group_natural(normalized, "train")
    eval_groups = _group_natural(normalized, "eval")

    def blocked(*reasons: str) -> dict:
        return {"status": "NOTRUN", "reasons": list(reasons)}

    def ready(*details: str) -> dict:
        return {"status": "READY_PROTOCOL", "reasons": list(details)}

    result = {
        "single_consensus": blocked("no_consensus_rows"),
        "single_train_medoid": blocked("no_eligible_train_copies"),
        "k4_natural_prototypes": blocked("no_eligible_train_copies"),
        "random4_natural_prototypes": blocked("no_eligible_train_copies"),
        "basic_sequence_features": blocked("no_eligible_natural_rows"),
        "glm_embedding": blocked("no_explicit_glm_embeddings"),
        "training_copy_profile_hmm": blocked("no_profile_hmm_inputs"),
    }
    if audit["status"] in {"BLOCKED_IDENTITY_FIELDS", "NOTRUN_NO_NATURAL_COPIES", "NOTRUN_NO_INPUT"}:
        reason = "identity_audit_%s" % audit["status"].lower()
        for name in result:
            result[name] = blocked(reason)
        return {
            "protocols": result,
            "counts": {
                "natural": _content_counts(natural),
                "complete": _content_counts(complete),
                "train": _content_counts(train_rows),
                "cal": _content_counts(cal_rows),
                "eval": _content_counts(eval_rows),
                "consensus": _content_counts(consensus),
            },
        }

    if consensus and eval_rows and all(has_content(row) for row in consensus + eval_rows):
        result["single_consensus"] = ready("one_consensus_prototype_per_family")
    elif not consensus:
        result["single_consensus"] = blocked("no_consensus_rows")
    elif not eval_rows:
        result["single_consensus"] = blocked("no_complete_eval_copies")
    else:
        result["single_consensus"] = blocked("consensus_or_eval_sequence_unavailable")

    k4_families = sorted(
        family for family, family_rows in train_groups.items()
        if len({canonical_copy_key(row) for row in family_rows}) >= 4
    )
    single_train_families = sorted(
        family for family, family_rows in train_groups.items()
        if len({canonical_copy_key(row) for row in family_rows}) >= 1
    )
    if not cal_rows or not eval_rows:
        result["single_train_medoid"] = blocked("missing_cal_or_eval_rows")
    elif not single_train_families:
        result["single_train_medoid"] = blocked("no_distinct_train_copies")
    elif any(not has_content(row) for row in train_rows + cal_rows + eval_rows):
        result["single_train_medoid"] = blocked("natural_copy_sequence_unavailable")
    else:
        result["single_train_medoid"] = ready("at_least_one_distinct_train_copy_per_family", *single_train_families)
    if not cal_rows or not eval_rows:
        reason = "missing_cal_or_eval_rows"
        result["k4_natural_prototypes"] = blocked(reason)
        result["random4_natural_prototypes"] = blocked(reason)
    elif not k4_families:
        result["k4_natural_prototypes"] = blocked("fewer_than_four_distinct_train_copies_per_family")
        result["random4_natural_prototypes"] = blocked("fewer_than_four_distinct_train_copies_per_family")
    elif any(not has_content(row) for row in train_rows + cal_rows + eval_rows):
        result["k4_natural_prototypes"] = blocked("natural_copy_sequence_unavailable")
        result["random4_natural_prototypes"] = blocked("natural_copy_sequence_unavailable")
    else:
        result["k4_natural_prototypes"] = ready("families_with_at_least_four_distinct_train_copies", *k4_families)
        result["random4_natural_prototypes"] = ready("families_with_at_least_four_distinct_train_copies", *k4_families)

    if train_rows and cal_rows and eval_rows and all(has_content(row) for row in train_rows + cal_rows + eval_rows):
        result["basic_sequence_features"] = ready("natural_copy_train_cal_eval_content_available")
    elif not train_rows or not cal_rows or not eval_rows:
        result["basic_sequence_features"] = blocked("missing_train_cal_or_eval_rows")
    else:
        result["basic_sequence_features"] = blocked("natural_copy_sequence_unavailable")

    glm_rows = [row for row in normalized if row["source_kind"] in NATURAL_COPY_KINDS]
    missing_glm = [row for row in glm_rows if missing(row["embedding_path"]) or missing(row["embedding_model_id"])]
    if glm_rows and not missing_glm and all(Path(row["embedding_path"]).is_file() for row in glm_rows):
        result["glm_embedding"] = ready("explicit_model_id_and_embedding_path_for_every_natural_copy")
    else:
        result["glm_embedding"] = blocked("explicit_glm_embedding_table_not_available")

    hmm_rows = [row for row in normalized if row["source_kind"] in CONSENSUS_KINDS or row["source_kind"] in NATURAL_COPY_KINDS]
    if hmm_rows and all(not missing(row["profile_path"]) and Path(row["profile_path"]).is_file() for row in hmm_rows):
        result["training_copy_profile_hmm"] = ready("explicit_profile_hmm_for_every_comparison_family")
    else:
        result["training_copy_profile_hmm"] = blocked("profile_hmm_inputs_not_available")

    return {
        "protocols": result,
        "counts": {
            "natural": _content_counts(natural),
            "complete": _content_counts(complete),
            "train": _content_counts(train_rows),
            "cal": _content_counts(cal_rows),
            "eval": _content_counts(eval_rows),
            "consensus": _content_counts(consensus),
            "consensus_families": consensus_families,
            "eval_families": sorted(eval_groups),
        },
    }


def protocol_contract() -> dict:
    """Fixed comparison specification shared by all future representations."""

    return {
        "contract_version": CONTRACT_VERSION,
        "seed": SEED,
        "question": "Does one consensus per family limit identity-aware TE retrieval compared with multiple natural-copy prototypes?",
        "identity_rules": {
            "natural_copy_required_fields": list(IDENTITY_FIELDS),
            "copy_key": "(host_id, source_copy_id)",
            "homology_key": "homology_component_id",
            "empty_ids": "unknown; never a same-copy positive and never used to infer identity",
            "consensus_fragments": "prototype material only; never independent natural copies",
            "split_rule": "source-copy and homology component must not cross train/cal/eval; host is contextual",
        },
        "protocols": {
            "single_consensus": {
                "prototype_source": "one explicit consensus row per family",
                "query_source": "natural genomic copies in EVAL",
            },
            "single_train_medoid": {
                "prototype_source": "one distinct TRAIN natural copy per family",
                "selection": "deterministic greedy PAM-style k-medoids in TRAIN k-mer space with k=1",
            },
            "k4_natural_prototypes": {
                "prototype_source": "four distinct TRAIN natural copies per family",
                "selection": "deterministic greedy PAM-style k-medoids in TRAIN k-mer space",
            },
            "random4_natural_prototypes": {
                "prototype_source": "four distinct TRAIN natural copies per family",
                "selection": "seed 42 random sample after identity filtering",
            },
            "basic_sequence_features": {
                "representation": "fixed sequence k-mer features",
                "fit_split": "TRAIN only; threshold fixed on CAL",
            },
            "glm_embedding": {
                "representation": "explicit frozen GLM embedding table with model_id",
                "random_embedding_policy": "forbidden",
            },
            "training_copy_profile_hmm": {
                "representation": "profile HMM trained from TRAIN natural copies",
                "test_copy_policy": "EVAL copies never enter profile construction",
            },
        },
        "calibration": {
            "cal_split": "CAL",
            "max_false_accept_rate": 0.01,
            "minimum_negative_pairs": 100,
            "threshold_rule": "choose the lowest tested score threshold whose CAL false-accept rate is at most 0.01; report ties deterministically",
            "same_budget_across_protocols": True,
        },
        "reporting": {
            "primary": ["family_macro_recall", "family_macro_precision", "family_macro_f1", "top1_accuracy"],
            "identity_strata": ["host", "source_copy", "homology_component", "family", "sequence_length"],
            "required_status_separation": ["engineering_ready", "numeric_valid", "scientific_pass", "generalization_pass"],
        },
    }


def calibrated_threshold(scores: Sequence[float], labels: Sequence[int], max_false_accept_rate: float = 0.01) -> float:
    """Return a deterministic threshold under a fixed CAL false-accept budget.

    This helper is intentionally independent of a representation.  It is not
    called by the default audit command, because no real score table exists
    in this checkout.
    """

    if len(scores) != len(labels) or not scores:
        raise ValueError("scores and labels must be non-empty and have equal length")
    negatives = sum(1 for label in labels if not label)
    if negatives == 0:
        raise ValueError("CAL threshold requires at least one negative pair")
    if not 0 <= max_false_accept_rate <= 1:
        raise ValueError("max_false_accept_rate must lie in [0,1]")
    candidates = sorted(set(float(score) for score in scores), reverse=True)
    acceptable = []
    for threshold in candidates:
        fp = sum(1 for score, label in zip(scores, labels) if not label and score >= threshold)
        tp = sum(1 for score, label in zip(scores, labels) if label and score >= threshold)
        if fp / float(negatives) <= max_false_accept_rate:
            acceptable.append((tp, -threshold, threshold))
    if not acceptable:
        return math.inf
    acceptable.sort(reverse=True)
    return acceptable[0][2]


def write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(str(temporary), str(path))


def write_inventory(path: Path, rows: Sequence[Mapping[str, object]]) -> None:
    fields = (
        "record_id", "source_kind", "assembly", "host_id", "host_locus", "source_copy_id",
        "homology_component_id", "family_id", "family_level", "split", "sequence_path",
        "embedding_path", "embedding_model_id", "profile_path", "origin_id",
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, delimiter="\t", extrasaction="ignore")
        writer.writeheader()
        for index, row in enumerate(rows):
            writer.writerow(normalize_row(row, index))


def run(input_manifest: Optional[Path], out_dir: Path) -> dict:
    """Write an audit-only result; absent input is a typed NOTRUN outcome."""

    out_dir.mkdir(parents=True, exist_ok=True)
    write_json(out_dir / "protocol_contract.json", protocol_contract())
    if input_manifest is None:
        audit = audit_manifest([])
        availability = protocol_availability([], audit)
        status = {
            "status": "NOTRUN_INPUT_MISSING",
            "reason": "no identity-aware manifest was supplied; no sequence, embedding, or HMM was fabricated",
            "input_manifest": None,
            "audit": audit,
            "protocol_availability": availability,
            "scores_written": False,
            "scientific_claim_status": "NOTRUN",
        }
        write_json(out_dir / "status.json", status)
        write_inventory(out_dir / "input_inventory.tsv", [])
        return status
    if not input_manifest.is_file():
        raise FileNotFoundError(str(input_manifest))
    raw = load_rows(input_manifest)
    normalized = [normalize_row(row, index) for index, row in enumerate(raw)]
    audit = audit_manifest(normalized)
    availability = protocol_availability(normalized, audit)
    write_inventory(out_dir / "input_inventory.tsv", normalized)
    status_name = "READY_FOR_BOUNDED_RUN" if audit["status"] == "PASS_AUDIT" else audit["status"]
    status = {
        "status": status_name,
        "input_manifest": str(input_manifest),
        "audit": audit,
        "protocol_availability": availability,
        "scores_written": False,
        "scientific_claim_status": "NOTRUN",
    }
    write_json(out_dir / "status.json", status)
    return status


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-manifest", type=Path)
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args(argv)
    run(args.input_manifest, args.out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
